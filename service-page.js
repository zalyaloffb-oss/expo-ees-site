function watchPageTextDecoding() {
  const observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      if (mutation.type === "characterData") {
        const decoded = decodeVisibleText(mutation.target.nodeValue);
        if (decoded !== mutation.target.nodeValue) mutation.target.nodeValue = decoded;
        return;
      }
      mutation.addedNodes.forEach((node) => {
        if (node.nodeType === Node.TEXT_NODE) {
          const decoded = decodeVisibleText(node.nodeValue);
          if (decoded !== node.nodeValue) node.nodeValue = decoded;
        } else if (node.nodeType === Node.ELEMENT_NODE) {
          decodeDomText(node);
        }
      });
    });
  });
  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true
  });
}





