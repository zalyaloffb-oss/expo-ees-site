function escapeHtml(value) {
  return decodeVisibleText(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function decodeDomText(scope) {
  const walker = document.createTreeWalker(scope, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    const decoded = decodeVisibleText(node.nodeValue);
    if (decoded !== node.nodeValue) node.nodeValue = decoded;
  });

  scope.querySelectorAll("[alt], [aria-label], [title]").forEach((element) => {
    ["alt", "aria-label", "title"].forEach((attr) => {
      if (element.hasAttribute(attr)) {
        const current = element.getAttribute(attr);
        const decoded = decodeVisibleText(current);
        if (decoded !== current) element.setAttribute(attr, decoded);
      }
    });
  });
}

