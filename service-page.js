function decodeVisibleText(value) {
  return readableTextFix.decode(value);
}

function escapeHtml(value) {
  return decodeVisibleText(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}





function decodeDataText(value, seen = new WeakSet()) {
  if (typeof value === "string") return decodeVisibleText(value);
  if (!value || typeof value !== "object") return value;
  if (seen.has(value)) return value;
  seen.add(value);
  if (Array.isArray(value)) {
    value.forEach((item, index) => {
      value[index] = decodeDataText(item, seen);
    });
    return value;
  }
  Object.keys(value).forEach((key) => {
    value[key] = decodeDataText(value[key], seen);
  });
  return value;
}

