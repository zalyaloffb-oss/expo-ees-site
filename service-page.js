function getArticleGalleryImages(article) {
  const sources = [];
  const add = (url) => {
    const value = String(url || "").trim();
    if (!value || sources.includes(value)) return;
    sources.push(value);
  };

  (article.gallery || article.images || []).forEach(add);

  const baseImage = normalizeArticleImageUrl(article.image);
  if (baseImage && Array.isArray(portfolioProjects)) {
    const articleFolder = baseImage.slice(0, baseImage.lastIndexOf("/") + 1);
    const matchedProject = portfolioProjects.find((project) => {
      const images = project.images || [];
      return images.some((image) => {
        const normalized = normalizeArticleImageUrl(image);
        return normalized === baseImage || (articleFolder && normalized.startsWith(articleFolder));
      });
    });
    (matchedProject?.images || []).forEach(add);
  }

  const uploadMatch = baseImage.match(/^(https:\/\/expo-ees\.ru\/wp-content\/uploads\/\d{4}\/\d{2}\/)([^/?#]+?)(\.[a-z0-9]+)$/i);
  if (uploadMatch) {
    const [, folder, fileBase, ext] = uploadMatch;
    if (/^\d+(?:-\d+)?$/.test(fileBase)) {
      for (let index = 1; index <= 12; index += 1) {
        add(`${folder}${index}${ext}`);
        add(`${folder}${index}-1${ext}`);
        add(`${folder}${index}-2${ext}`);
        add(`${folder}${index}-768x512${ext}`);
        add(`${folder}${index}-1-768x512${ext}`);
        add(`${folder}${index}-2-768x512${ext}`);
      }
    }
  }

  add(article.image);
  add(baseImage);
  return sources.slice(0, 48);
}

